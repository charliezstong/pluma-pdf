export const catalogs = { en, es, pt } as const;

export function normalizeLocale(language: string): Locale | undefined {
  const base = language.trim().toLowerCase().replace(/_/g, '-').split('-')[0];
  return base === 'en' || base === 'es' || base === 'pt' ? base : undefined;
}

export function isLanguagePreference(value: unknown): value is LanguagePreference {
  return value === 'auto' || value === 'en' || value === 'es' || value === 'pt';
}

export function resolveLocale(preferences: readonly string[], override?: string): Locale {
  const manual = typeof override === 'string' ? normalizeLocale(override) : undefined;
  if (manual) return manual;
  for (const preference of preferences) {
    const supported = normalizeLocale(preference);
    if (supported) return supported;
  }
  return 'en';
}

export function interpolate(template: string, values: TranslationValues = {}): string {
  return template.replace(/\{([A-Za-z][A-Za-z0-9_]*)\}/g, (token, name: string) =>
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : token);
}

export function t(locale: Locale, key: TranslationKey, values?: TranslationValues): string {
  const selected: Readonly<Record<string, string>> = catalogs[locale] ?? catalogs.en;
  return interpolate(selected[key] ?? catalogs.en[key] ?? key, values);
}
